#!/usr/bin/env node
// gen-unit-routing.mjs — generate the app repo's UNIT-test routing from suites-manifest.json.
//
// WHY: the unit gate (starlabs-development/.github/workflows/unit-tests.yml) must run only the unit specs
// belonging to the systems a diff touches — the same routing e2e already gets from the manifest. Hand-copying
// `appPaths` into a workflow creates a SECOND source of truth that drifts silently: someone adds a module to
// the manifest, the unit gate never learns about it, and the gate goes green while testing none of the
// changed code. That is the false-green class this repo exists to close, so the routing is GENERATED and
// drift is CHECKED, never maintained by hand.
//
// Writes two files into the app repo, both from the same source:
//   .github/unit-filters.yml   — dorny/paths-filter filter definitions (which systems a diff touches)
//   .github/unit-routing.json  — system -> unit-spec include globs (which specs to run)
//
// Usage (paths mirror check-suite-coverage.mjs):
//   node scripts/gen-unit-routing.mjs                      # write both files
//   node scripts/gen-unit-routing.mjs --check              # exit 1 if either file is stale (CI use)
//   node scripts/gen-unit-routing.mjs --app=../some-checkout
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HUB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, dflt) => {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : dflt;
};
const APP = path.resolve(HUB, arg('app', '../starlabs-development'));
const CHECK = process.argv.includes('--check');

const manifest = JSON.parse(fs.readFileSync(path.join(HUB, 'suites-manifest.json'), 'utf8'));

// Only ciReady suites gate. A suite with ciReady:false (today: support) has no emulator config and is not a
// gate yet — routing to it would promise a run that cannot happen.
const suites = Object.entries(manifest.suites)
  .filter(([, s]) => s.ciReady !== false && Array.isArray(s.appPaths) && s.appPaths.length);

/** appPath glob -> the unit-spec glob underneath it. Negations are routing-only and never produce specs. */
const toSpecGlob = (g) => {
  if (g.startsWith('!')) return null;
  if (g.endsWith('/**')) return `${g.slice(0, -3)}/**/*.unit.spec.ts`;
  if (g.endsWith('.ts')) return g.replace(/\.ts$/, '.unit.spec.ts');
  return `${g}/**/*.unit.spec.ts`;
};

// ---- .github/unit-filters.yml (dorny/paths-filter) -------------------------------------------------
// `_all` is the cross-cutting fallback: the manifest says a match there "can affect ANYTHING", so it runs
// every unit spec rather than a routed subset.
const yml = [
  '# GENERATED by starlabs-e2e-tests/scripts/gen-unit-routing.mjs — DO NOT EDIT BY HAND.',
  '# Source of truth: suites-manifest.json (appPaths per suite + crossCutting.appPaths).',
  '# Regenerate:  node scripts/gen-unit-routing.mjs',
  '# Verify:      node scripts/gen-unit-routing.mjs --check',
  '',
  '# Cross-cutting: a match here can affect anything, so the gate runs EVERY unit spec.',
  '_all:',
  ...(manifest.crossCutting?.appPaths ?? []).map((g) => `  - '${g}'`),
  `  - 'tsconfig*.json'`,
  `  - 'karma.ci.conf.js'`,
  '',
  ...suites.flatMap(([name, s]) => [`${name}:`, ...s.appPaths.map((g) => `  - '${g}'`), '']),
].join('\n');

// ---- .github/unit-routing.json (system -> include globs) ------------------------------------------
const routing = {
  _generatedBy: 'starlabs-e2e-tests/scripts/gen-unit-routing.mjs — do not edit by hand',
  _source: 'suites-manifest.json',
  systems: Object.fromEntries(
    suites.map(([name, s]) => [name, [...new Set(s.appPaths.map(toSpecGlob).filter(Boolean))]]),
  ),
};
const json = JSON.stringify(routing, null, 2) + '\n';

// ---- write or check --------------------------------------------------------------------------------
const targets = [
  [path.join(APP, '.github', 'unit-filters.yml'), yml],
  [path.join(APP, '.github', 'unit-routing.json'), json],
];

if (CHECK) {
  let stale = 0;
  for (const [file, want] of targets) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (have === want) { console.log(`ok    ${path.relative(APP, file)}`); continue; }
    stale++;
    console.error(have === null ? `MISSING ${file}` : `STALE   ${path.relative(APP, file)}`);
  }
  if (stale) {
    console.error(
      `\n${stale} routing file(s) out of date with suites-manifest.json.` +
      `\nThe unit gate would run the WRONG specs for a diff — regenerate:` +
      `\n  node scripts/gen-unit-routing.mjs`,
    );
    process.exit(1);
  }
  console.log('\nunit routing is in sync with suites-manifest.json');
} else {
  for (const [file, body] of targets) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body);
    console.log(`wrote ${path.relative(APP, file)}`);
  }
  console.log(`\n${suites.length} ciReady suites routed.`);
}
